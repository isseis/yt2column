// Package failure defines the contract for reporting the failure of an
// authenticated request: the Kind that classifies it, the Notice a report may
// carry, and the Notifier that posts it.
package failure

import "context"

// Kind classifies a failed authenticated request. The zero value is
// KindUnknown.
type Kind int

// The constants classify a failed authenticated request, in the order the
// failure text and the classification switch are written against.
const (
	KindUnknown Kind = iota
	KindBodyTooLarge
	KindInvalidBody
	KindInvalidVideoURL
	KindInvalidTranscript
	KindTranscriptTooLong // the prompt built from the transcript exceeds the limit
	KindLLMTimeout
	KindLLMEmpty
	KindLLMTruncated
	KindLLM     // any other failure of an LLM call in the write stage
	KindPublish // the article post failed, possibly after some messages
	KindInternal
)

// Notice is everything a failure post may contain. Every field is chosen or
// generated by the server; none is copied from the request.
type Notice struct {
	RequestID string
	VideoID   string // validated; "" when no video ID was derived
	Kind      Kind
}

// Notifier posts a Notice.
type Notifier interface {
	Notify(ctx context.Context, n Notice) error
}

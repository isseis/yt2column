const (
	// Observed first-line headers for CodeRabbit status comments excluded from
	// mention findings across all three PR endpoints.
	codeRabbitHeaderGenerated   = "<!-- coderabbit-ai-generated:v1 -->"
	codeRabbitHeaderCodingAgent = "<!-- This is an auto-generated comment: coding agent status by CodeRabbit -->"

	// Observed first-line fragments for Sourcery conversation comments excluded
	// from mention findings (issues/<PR>/comments only).
	sourceryGuidePrefix  = "<!-- Generated by "
	sourceryGuideSuffix  = ": start review_guide -->"
	sourceryBudgetPrefix = "Sorry @"
	sourceryBudgetMid    = ", you've used your own review budget of "
	sourceryBudgetSuffix = " diff characters for the last 7 days."
)

// ObservedBot binds a ReviewProfile to its GraphQL reviewer login (without
// [bot]) for observed status-comment exclusion in PRMentions.
type ObservedBot struct {
	Profile  ReviewProfile
	Reviewer Login
}

// ParseObservedBot parses "<profile>=<login>" without repairing either half.
// Its errors wrap ErrInvalidInput and name the rule only, never the input.
func ParseObservedBot(s string) (ObservedBot, error) {
	profileRaw, loginRaw, ok := strings.Cut(s, "=")
	if !ok {
		return ObservedBot{}, fmt.Errorf("%w: observed bot grammar", ErrInvalidInput)
	}
	profile, err := ParseReviewProfile(profileRaw)
	if err != nil {
		return ObservedBot{}, err
	}
	reviewer, err := ParseLogin(loginRaw)
	if err != nil {
		return ObservedBot{}, err
	}
	return ObservedBot{Profile: profile, Reviewer: reviewer}, nil
}

// MentionScanRequest names the PR, the observed bots whose status comments may
// be excluded, and the accepted manual request texts whose comments by the
// authenticated user are excluded from mention findings.
type MentionScanRequest struct {
	PR           PRNumber
	ObservedBots []ObservedBot // 1 or more, unique profiles and unique logins
	Requests     []string      // 1 or more accepted manual request texts
}

// MentionScanState reports whether PRMentions completed cleanly. The zero value
// is MentionScanUnreadable so an uninitialized MentionScanResult fails closed.
type MentionScanState int

// States of a mention scan.
const (
	MentionScanUnreadable MentionScanState = iota // "unreadable"
	MentionScanOK                                 // "ok"
)

// MarshalText encodes the scan state and rejects values outside the declared set.
func (s MentionScanState) MarshalText() ([]byte, error) {
	switch s {
	case MentionScanUnreadable:
		return []byte("unreadable"), nil
	case MentionScanOK:
		return []byte("ok"), nil
	default:
		return nil, fmt.Errorf("%w: mention scan state", errUnknownEnum)
	}
}

// MentionScanStates lists every declared MentionScanState, for the guide's
// document guard.
func MentionScanStates() []MentionScanState {
	return []MentionScanState{MentionScanUnreadable, MentionScanOK}
}

// MentionSource identifies which PR endpoint produced a MentionFinding. The
// zero value MentionSourceUnknown is invalid so an unset source cannot be
// marshaled.
type MentionSource int

// Sources of a mention finding.
const (
	MentionSourceUnknown      MentionSource = iota // invalid
	MentionSourceIssueComment                      // "issue-comment"
	MentionSourceLineComment                       // "line-comment"
	MentionSourceReview                            // "review"
)

// MarshalText encodes the source name and rejects MentionSourceUnknown and any
// value outside the declared set.
func (s MentionSource) MarshalText() ([]byte, error) {
	switch s {
	case MentionSourceIssueComment:
		return []byte("issue-comment"), nil
	case MentionSourceLineComment:
		return []byte("line-comment"), nil
	case MentionSourceReview:
		return []byte("review"), nil
	default:
		return nil, fmt.Errorf("%w: mention source", errUnknownEnum)
	}
}

// MentionSources lists every valid MentionSource, for the guide's document
// guard.
func MentionSources() []MentionSource {
	return []MentionSource{MentionSourceIssueComment, MentionSourceLineComment, MentionSourceReview}
}

// MentionScanStage identifies which read stage failed when State is
// MentionScanUnreadable. The zero value is empty and used on MentionScanOK.
type MentionScanStage int

// Stages of a mention scan.
const (
	MentionStageNone          MentionScanStage = iota // ""
	MentionStageRepo                                  // "repo"
	MentionStageUser                                  // "user"
	MentionStageIssueComments                         // "issue-comments"
	MentionStageLineComments                          // "line-comments"
	MentionStageReviews                               // "reviews"
)

// MarshalText encodes the stage name and rejects values outside the declared set.
func (s MentionScanStage) MarshalText() ([]byte, error) {
	switch s {
	case MentionStageNone:
		return []byte(""), nil
	case MentionStageRepo:
		return []byte("repo"), nil
	case MentionStageUser:
		return []byte("user"), nil
	case MentionStageIssueComments:
		return []byte("issue-comments"), nil
	case MentionStageLineComments:
		return []byte("line-comments"), nil
	case MentionStageReviews:
		return []byte("reviews"), nil
	default:
		return nil, fmt.Errorf("%w: mention scan stage", errUnknownEnum)
	}
}

// MentionScanStages lists every non-empty MentionScanStage, for the guide's
// document guard.
func MentionScanStages() []MentionScanStage {
	return []MentionScanStage{
		MentionStageRepo, MentionStageUser, MentionStageIssueComments,
		MentionStageLineComments, MentionStageReviews,
	}
}

// MentionFinding records one PR comment or review whose body contains a
// rejected mention and was not excluded as an observed bot status comment or
// an accepted manual request. No body text is stored or emitted.
type MentionFinding struct {
	Source    MentionSource `json:"source"`
	URL       string        `json:"url"`
	CreatedAt string        `json:"createdAt"`           // review: submitted_at, or "" when null/absent
	UpdatedAt string        `json:"updatedAt,omitempty"` // omitted for MentionSourceReview
	ByUser    bool          `json:"byUser"`
	ByBot     bool          `json:"byBot"`
}

// MentionScanResult is the output of mentions. Mentions is always a non-nil
// slice, ordered by source (issue-comment, line-comment, review) and API order
// within each source.
type MentionScanResult struct {
	Protocol int              `json:"protocol"`
	State    MentionScanState `json:"state"`
	Reason   UnreadableReason `json:"reason"`
	Stage    MentionScanStage `json:"stage"`
	Mentions []MentionFinding `json:"mentions"`
}

// PRMentions scans conversation comments, line comments, and PR reviews of req.PR
// for any value in RejectedMentions.
//
// Contract: caller argument errors (including zero, out-of-range, or duplicate
// ObservedBot entries or invalid Requests) return ErrInvalidInput before any gh
// call; every read, strict-JSON, or limit failure discards partial results and
// returns MentionScanUnreadable with Reason, Stage, and an empty Mentions
// slice; no comment or review body ever reaches the result or an error.
func (g *GitHub) PRMentions(ctx context.Context, req MentionScanRequest) (MentionScanResult, error) {
	if err := validateMentionScanRequest(req); err != nil {
		return MentionScanResult{}, err
	}
	ctx, cancel := context.WithTimeout(ctx, githubTimeout)
	defer cancel()

	owner, name, err := ghci.ResolveRepo(ctx, g.run)
	if err != nil {
		return unreadableMentions(repoErrorReason(ctx, err), MentionStageRepo), nil
	}

	r := &reviewReader{g: g, repo: repository{owner: owner, name: name}, pr: req.PR}
	user, failure := r.readUser(ctx)
	if failure != nil {
		return unreadableMentions(mentionFailureReason(ctx, failure), MentionStageUser), nil
	}

	var findings []MentionFinding
	issueFindings, failure := r.scanCommentMentions(ctx, "issues/"+req.PR.String()+"/comments", MentionSourceIssueComment, user, req)
	if failure != nil {
		return unreadableMentions(mentionFailureReason(ctx, failure), MentionStageIssueComments), nil
	}
	findings = append(findings, issueFindings...)

	lineFindings, failure := r.scanCommentMentions(ctx, "pulls/"+req.PR.String()+"/comments", MentionSourceLineComment, user, req)
	if failure != nil {
		return unreadableMentions(mentionFailureReason(ctx, failure), MentionStageLineComments), nil
	}
	findings = append(findings, lineFindings...)

	reviewFindings, failure := r.scanReviewMentions(ctx, user, req)
	if failure != nil {
		return unreadableMentions(mentionFailureReason(ctx, failure), MentionStageReviews), nil
	}
	findings = append(findings, reviewFindings...)

	if findings == nil {
		findings = []MentionFinding{}
	}
	return MentionScanResult{
		Protocol: Protocol,
		State:    MentionScanOK,
		Mentions: findings,
	}, nil
}

func unreadableMentions(reason UnreadableReason, stage MentionScanStage) MentionScanResult {
	return MentionScanResult{
		Protocol: Protocol,
		State:    MentionScanUnreadable,
		Reason:   reason,
		Stage:    stage,
		Mentions: []MentionFinding{},
	}
}

func repoErrorReason(ctx context.Context, err error) UnreadableReason {
	if errors.Is(ctx.Err(), context.DeadlineExceeded) {
		return UnreadableCall
	}
	if repoErr, ok := errors.AsType[*ghci.RepoError](err); ok {
		switch repoErr.Reason {
		case ghci.UnreadableCall:
			return UnreadableCall
		case ghci.UnreadableRejected:
			return UnreadableRejected
		case ghci.UnreadableLimit:
			return UnreadableLimit
		default:
			return UnreadableRejected
		}
	}
	return UnreadableCall
}

func mentionFailureReason(ctx context.Context, failure *reviewError) UnreadableReason {
	if errors.Is(ctx.Err(), context.DeadlineExceeded) {
		return UnreadableCall
	}
	return failure.reason
}

func validateMentionScanRequest(req MentionScanRequest) error {
	if !req.PR.usable() {
		return fmt.Errorf("%w: PR number", ErrInvalidInput)
	}
	if len(req.ObservedBots) == 0 {
		return fmt.Errorf("%w: observed bots empty", ErrInvalidInput)
	}
	seenProfiles := make(map[ReviewProfile]struct{}, len(req.ObservedBots))
	seenLogins := make(map[Login]struct{}, len(req.ObservedBots))
	for _, bot := range req.ObservedBots {
		if !bot.Profile.usable() {
			return fmt.Errorf("%w: observed bot profile", ErrInvalidInput)
		}
		if !bot.Reviewer.usable() {
			return fmt.Errorf("%w: observed bot reviewer", ErrInvalidInput)
		}
		if _, dup := seenProfiles[bot.Profile]; dup {
			return fmt.Errorf("%w: observed bot profile named twice", ErrInvalidInput)
		}
		if _, dup := seenLogins[bot.Reviewer]; dup {
			return fmt.Errorf("%w: observed bot reviewer named twice", ErrInvalidInput)
		}
		seenProfiles[bot.Profile] = struct{}{}
		seenLogins[bot.Reviewer] = struct{}{}
	}
	return validateRequestTexts(req.Requests)
}

// validateRequestTexts enforces that requests is non-empty, each entry is 1 to
// maxRequestTextLength bytes without leading or trailing whitespace, and no
// entry repeats.
func validateRequestTexts(requests []string) error {
	if len(requests) == 0 {
		return fmt.Errorf("%w: request list empty", ErrInvalidInput)
	}
	seen := make(map[string]struct{}, len(requests))
	for _, text := range requests {
		if text == "" || len(text) > maxRequestTextLength || strings.TrimSpace(text) != text {
			return fmt.Errorf("%w: request text", ErrInvalidInput)
		}
		if _, dup := seen[text]; dup {
			return fmt.Errorf("%w: request text named twice", ErrInvalidInput)
		}
		seen[text] = struct{}{}
	}
	return nil
}

func (r *reviewReader) scanCommentMentions(
	ctx context.Context,
	path string,
	source MentionSource,
	user string,
	req MentionScanRequest,
) ([]MentionFinding, *reviewError) {
	var findings []MentionFinding
	failure := r.restPages(ctx, path, func(item strictjson.Value) error {
		obj, err := item.AsObject()
		if err != nil {
			return rejected("comment")
		}
		members, err := obj.Collect("id", keyUser, keyBody, "created_at", "updated_at", "html_url")
		if err != nil {
			return rejected("comment")
		}
		if _, err := positiveInt64Member(members, "id"); err != nil {
			return err
		}
		login, kind, err := userMember(members)
		if err != nil {
			return err
		}
		body, _, err := nullableStringMember(members, keyBody)
		if err != nil {
			return rejected("comment body")
		}
		created, err := timeMember(members, "created_at")
		if err != nil {
			return err
		}
		updated, err := timeMember(members, "updated_at")
		if err != nil {
			return err
		}
		url, err := strictjson.RequiredString(members, "html_url")
		if err != nil || !validCommentURL(url) {
			return rejected("comment html_url")
		}
		if finding, ok := classifyMention(source, kind, login, user, body, url, formatReviewTime(created), formatReviewTime(updated), req); ok {
			findings = append(findings, finding)
		}
		return nil
	})
	return findings, failure
}

func (r *reviewReader) scanReviewMentions(
	ctx context.Context,
	user string,
	req MentionScanRequest,
) ([]MentionFinding, *reviewError) {
	var findings []MentionFinding
	failure := r.restPages(ctx, "pulls/"+r.pr.String()+"/reviews", func(item strictjson.Value) error {
		obj, err := item.AsObject()
		if err != nil {
			return rejected("review")
		}
		members, err := obj.Collect("id", keyUser, keyBody, "submitted_at", "html_url")
		if err != nil {
			return rejected("review")
		}
		if _, err := positiveInt64Member(members, "id"); err != nil {
			return err
		}
		login, kind, err := userMember(members)
		if err != nil {
			return err
		}
		body, _, err := nullableStringMember(members, keyBody)
		if err != nil {
			return rejected("review body")
		}
		submitted, err := optionalTimeMember(members, "submitted_at")
		if err != nil {
			return err
		}
		url, err := strictjson.RequiredString(members, "html_url")
		if err != nil || !validCommentURL(url) {
			return rejected("review html_url")
		}
		createdAt := ""
		if submitted != nil {
			createdAt = formatReviewTime(*submitted)
		}
		if finding, ok := classifyMention(MentionSourceReview, kind, login, user, body, url, createdAt, "", req); ok {
			findings = append(findings, finding)
		}
		return nil
	})
	return findings, failure
}

// classifyMention decides whether one item produces a MentionFinding.
// Contract: observed bot status comments and (for conversation comments only)
// accepted manual requests from the authenticated user are excluded; every
// other item whose body contains a RejectedMentions value is reported with
// ByUser/ByBot flags and never with body text.
func classifyMention(
	source MentionSource,
	kind, login, user, body, url, createdAt, updatedAt string,
	req MentionScanRequest,
) (MentionFinding, bool) {
	if isObservedBotComment(source, kind, login, user, body, req.ObservedBots) {
		return MentionFinding{}, false
	}
	if source == MentionSourceIssueComment && isRequestComment(kind, login, user, body, req.Requests) {
		return MentionFinding{}, false
	}
	if !containsRejectedMention(body) {
		return MentionFinding{}, false
	}
	return MentionFinding{
		Source:    source,
		URL:       url,
		CreatedAt: createdAt,
		UpdatedAt: updatedAt,
		ByUser:    kind == typenameUser && login == user,
		ByBot:     kind == typenameBot,
	}, true
}

// isObservedBotComment reports whether an item is an observed status comment
// from one of bots. Contract: only a Bot whose REST login equals
// "<reviewer>[bot]" and whose first line (after stripping a single trailing CR)
// matches an observed header for its declared profile is excluded; a User with
// a matching login or any non-matching header is never excluded.
func isObservedBotComment(source MentionSource, kind, login, user, body string, bots []ObservedBot) bool {
	if kind != typenameBot {
		return false
	}
	line1 := firstLine(body)
	for _, bot := range bots {
		if login != bot.Reviewer.String()+botLoginSuffix {
			continue
		}
		switch bot.Profile {
		case ProfileCodeRabbit:
			return line1 == codeRabbitHeaderGenerated || line1 == codeRabbitHeaderCodingAgent
		case ProfileSourcery:
			if source != MentionSourceIssueComment {
				return false
			}
			guideHeader := sourceryGuidePrefix + bot.Reviewer.String() + botLoginSuffix + sourceryGuideSuffix
			return line1 == guideHeader || isSourceryBudgetLine(line1, user)
		default:
			return false
		}
	}
	return false
}

// firstLine returns the text before the first LF with at most one trailing CR
// removed.
func firstLine(body string) string {
	line, _, _ := strings.Cut(body, "\n")
	return strings.TrimSuffix(line, "\r")
}

// isSourceryBudgetLine matches Sourcery's observed 7-day budget notice first
// line for the authenticated user:
// "Sorry @<user>, you've used your own review budget of <digits/commas> diff characters for the last 7 days."
func isSourceryBudgetLine(line, user string) bool {
	prefix := sourceryBudgetPrefix + user + sourceryBudgetMid
	rest, ok := strings.CutPrefix(line, prefix)
	if !ok {
		return false
	}
	amount, ok := strings.CutSuffix(rest, sourceryBudgetSuffix)
	if !ok {
		return false
	}
	return isBudgetDigits(amount)
}

// isBudgetDigits accepts one or more ASCII digits and commas starting and
// ending with an ASCII digit.
func isBudgetDigits(s string) bool {
	if s == "" || !isASCIIDigit(s[0]) || !isASCIIDigit(s[len(s)-1]) {
		return false
	}
	for i := range len(s) {
		if !isASCIIDigit(s[i]) && s[i] != ',' {
			return false
		}
	}
	return true
}

func isASCIIDigit(c byte) bool {
	return '0' <= c && c <= '9'
}

type msComment struct {
	id       int64
	login    string
	kind     string
	nullUser bool
	body     string
	nullBody bool
	created  string
	updated  string
	url      string
}

func (c msComment) json() map[string]any {
	created := c.created
	if created == "" {
		created = rsCreated
	}
	updated := c.updated
	if updated == "" {
		updated = created
	}
	var user any
	if !c.nullUser {
		user = map[string]any{keyLogin: c.login, keyType: c.kind, "id": 1}
	}
	var body any = c.body
	if c.nullBody {
		body = nil
	}
	return map[string]any{
		"id":         c.id,
		keyUser:      user,
		keyBody:      body,
		"created_at": created,
		"updated_at": updated,
		"html_url":   c.url,
	}
}

type msReview struct {
	id            int64
	login         string
	kind          string
	nullUser      bool
	body          string
	nullBody      bool
	submitted     string
	omitSubmitted bool
	url           string
}

func (r msReview) json() map[string]any {
	var user any
	if !r.nullUser {
		user = map[string]any{keyLogin: r.login, keyType: r.kind}
	}
	var body any = r.body
	if r.nullBody {
		body = nil
	}
	m := map[string]any{
		"id":       r.id,
		keyUser:    user,
		keyBody:    body,
		"html_url": r.url,
	}
	if !r.omitSubmitted {
		if r.submitted == "" {
			m["submitted_at"] = nil
		} else {
			m["submitted_at"] = r.submitted
		}
	}
	return m
}

type msInput struct {
	issueComments []msComment
	lineComments  []msComment
	reviews       []msReview
	edit          map[MentionScanStage]func(string) string
	fail          map[MentionScanStage]error
	stop          MentionScanStage
}

func (in msInput) restSteps(t testing.TB, stage MentionScanStage, path string, items []any) []cmdrunnertestutil.Step {
	t.Helper()
	var steps []cmdrunnertestutil.Step
	for page := 1; ; page++ {
		start := (page - 1) * restPerPage
		end := min(start+restPerPage, len(items))
		chunk := []any{}
		if start < len(items) {
			chunk = items[start:end]
		}
		body := mustJSON(t, chunk)
		if f := in.edit[stage]; f != nil {
			body = f(body)
		}
		out := includedOutput(http.StatusOK, []string{"Date: " + rsDate(t, rsNow)}, body)
		steps = append(steps, includeStep(path+"?per_page=100&page="+strconv.Itoa(page), out, in.fail[stage]))
		if in.fail[stage] != nil || len(chunk) < restPerPage {
			return steps
		}
	}
}

func (in msInput) steps(t testing.TB) []cmdrunnertestutil.Step {
	t.Helper()
	var steps []cmdrunnertestutil.Step
	repo := repoStep()
	if f := in.edit[MentionStageRepo]; f != nil {
		repo.Out = f(repo.Out)
	}
	if err := in.fail[MentionStageRepo]; err != nil {
		repo.Err = err
		return append(steps, repo)
	}
	steps = append(steps, repo)
	if in.stop == MentionStageRepo {
		return steps
	}

	userOut := `{"login":"` + rsUser + `","id":1}`
	if f := in.edit[MentionStageUser]; f != nil {
		userOut = f(userOut)
	}
	userStep := cmdrunnertestutil.Step{Name: "gh", Args: []string{ghAPI, ghUserEndpoint}, Out: userOut, Err: in.fail[MentionStageUser]}
	steps = append(steps, userStep)
	if in.fail[MentionStageUser] != nil || in.stop == MentionStageUser {
		return steps
	}

	issues := make([]any, 0, len(in.issueComments))
	for _, c := range in.issueComments {
		issues = append(issues, c.json())
	}
	steps = append(steps, in.restSteps(t, MentionStageIssueComments, "issues/"+testPR+"/comments", issues)...)
	if in.fail[MentionStageIssueComments] != nil || in.stop == MentionStageIssueComments {
		return steps
	}

	lines := make([]any, 0, len(in.lineComments))
	for _, c := range in.lineComments {
		lines = append(lines, c.json())
	}
	steps = append(steps, in.restSteps(t, MentionStageLineComments, "pulls/"+testPR+"/comments", lines)...)
	if in.fail[MentionStageLineComments] != nil || in.stop == MentionStageLineComments {
		return steps
	}

	reviews := make([]any, 0, len(in.reviews))
	for _, r := range in.reviews {
		reviews = append(reviews, r.json())
	}
	return append(steps, in.restSteps(t, MentionStageReviews, "pulls/"+testPR+"/reviews", reviews)...)
}

func runMentions(t *testing.T, req MentionScanRequest, in msInput) MentionScanResult {
	t.Helper()
	return runMentionsCtx(t.Context(), t, req, in)
}

func runMentionsCtx(ctx context.Context, t *testing.T, req MentionScanRequest, in msInput) MentionScanResult {
	t.Helper()
	g, err := NewGitHubWithoutReviewer(cmdrunnertestutil.New(t, in.steps(t)...))
	if err != nil {
		t.Fatalf("NewGitHubWithoutReviewer: %v", err)
	}
	got, err := g.PRMentions(ctx, req)
	if err != nil {
		t.Fatalf("PRMentions: %v", err)
	}
	return got
}

func TestPRMentions(t *testing.T) {
	t.Run("empty_lists_return_ok_with_non_nil_slice", func(t *testing.T) {
		got := runMentions(t, defaultMentionRequest(t), msInput{})
		want := MentionScanResult{Protocol: Protocol, State: MentionScanOK, Mentions: []MentionFinding{}}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("got = %s\nwant  %s", mustJSON(t, got), mustJSON(t, want))
		}
		if !strings.Contains(mustJSON(t, got), `"mentions":[]`) {
			t.Errorf("JSON lacks empty mentions array: %s", mustJSON(t, got))
		}
	})

	// All four rejected mentions (literal values, mixed case) across all three
	// endpoints and every author kind (authenticated user, other user, bot,
	// deleted null user), plus null body, null/omitted submitted_at, and
	// ordering by source then API order.
	t.Run("mentions_across_endpoints_authors_and_ordering", func(t *testing.T) {
		in := msInput{
			issueComments: []msComment{
				{id: 1, login: rsUser, kind: typenameUser, body: "note for @CODEX", created: at("10:01:00"), updated: at("10:02:00"), url: rsURL(1)},
				{id: 2, login: "mallory", kind: typenameUser, body: "hi @CodeRabbitAI", created: at("10:03:00"), url: rsURL(2)},
				{id: 3, nullUser: true, body: "ping @SOURCERY-AI", created: at("10:04:00"), url: rsURL(3)},
				{id: 4, login: rsUser, kind: typenameBot, body: "bot named like user @sourceryai", created: at("10:05:00"), url: rsURL(4)},
				{id: 5, login: "alice", kind: typenameUser, nullBody: true, created: at("10:06:00"), url: rsURL(5)},
				{id: 6, login: "alice", kind: typenameUser, body: "clean text", created: at("10:07:00"), url: rsURL(6)},
			},
			lineComments: []msComment{
				{id: 11, login: testSourceryBotLogin, kind: typenameBot, body: "diff quotes @sourcery-ai", created: at("10:08:00"), url: testCommentURL(11)},
				{id: 12, login: rsUser, kind: typenameUser, body: "@coderabbitai review", created: at("10:09:00"), url: testCommentURL(12)},
				{id: 13, login: "bob", kind: typenameUser, nullBody: true, created: at("10:10:00"), url: testCommentURL(13)},
			},
			reviews: []msReview{
				{id: 21, login: "bob", kind: typenameUser, body: "please @SourceryAI", submitted: at("10:11:00"), url: rsReviewURL(21)},
				{id: 22, login: "other-bot[bot]", kind: typenameBot, body: "calls @codex", submitted: "", url: rsReviewURL(22)},
				{id: 23, login: rsUser, kind: typenameUser, body: "@sourcery-ai review", omitSubmitted: true, url: rsReviewURL(23)},
				{id: 24, login: "carol", kind: typenameUser, nullBody: true, submitted: at("10:12:00"), url: rsReviewURL(24)},
			},
		}
		got := runMentions(t, defaultMentionRequest(t), in)
		want := MentionScanResult{
			Protocol: Protocol,
			State:    MentionScanOK,
			Mentions: []MentionFinding{
				{Source: MentionSourceIssueComment, URL: rsURL(1), CreatedAt: at("10:01:00"), UpdatedAt: at("10:02:00"), ByUser: true},
				{Source: MentionSourceIssueComment, URL: rsURL(2), CreatedAt: at("10:03:00"), UpdatedAt: at("10:03:00")},
				{Source: MentionSourceIssueComment, URL: rsURL(3), CreatedAt: at("10:04:00"), UpdatedAt: at("10:04:00")},
				{Source: MentionSourceIssueComment, URL: rsURL(4), CreatedAt: at("10:05:00"), UpdatedAt: at("10:05:00"), ByBot: true},
				{Source: MentionSourceLineComment, URL: testCommentURL(11), CreatedAt: at("10:08:00"), UpdatedAt: at("10:08:00"), ByBot: true},
				// Request text in a line comment or PR review is not excluded.
				{Source: MentionSourceLineComment, URL: testCommentURL(12), CreatedAt: at("10:09:00"), UpdatedAt: at("10:09:00"), ByUser: true},
				{Source: MentionSourceReview, URL: rsReviewURL(21), CreatedAt: at("10:11:00")},
				{Source: MentionSourceReview, URL: rsReviewURL(22), CreatedAt: "", ByBot: true},
				{Source: MentionSourceReview, URL: rsReviewURL(23), CreatedAt: "", ByUser: true},
			},
		}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("got = %s\nwant  %s", mustJSON(t, got), mustJSON(t, want))
		}
		// Review findings omit updatedAt in JSON.
		rawReview := mustJSON(t, got.Mentions[6])
		if strings.Contains(rawReview, "updatedAt") {
			t.Errorf("review finding JSON contains updatedAt: %s", rawReview)
		}
	})

	// Verify PRMentions wires isRequestComment for all three manual request
	// texts in issues/<PR>/comments (full edge-case matrix lives in
	// TestIsRequestComment) while retaining non-matching user comments.
	t.Run("manual_request_exclusions", func(t *testing.T) {
		in := msInput{
			issueComments: []msComment{
				{id: 1, login: rsUser, kind: typenameUser, body: "@coderabbitai review", url: rsURL(1)},
				{id: 2, login: rsUser, kind: typenameUser, body: " \r\n@sourcery-ai review\r\n ", url: rsURL(2)},
				{id: 3, login: rsUser, kind: typenameUser, body: "\t@sourceryai review\n", url: rsURL(3)},
				{id: 4, login: rsUser, kind: typenameUser, body: "@sourcery-ai review extra", url: rsURL(4)},
			},
		}
		got := runMentions(t, defaultMentionRequest(t), in)
		want := MentionScanResult{
			Protocol: Protocol,
			State:    MentionScanOK,
			Mentions: []MentionFinding{
				{Source: MentionSourceIssueComment, URL: rsURL(4), CreatedAt: rsCreated, UpdatedAt: rsCreated, ByUser: true},
			},
		}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("got = %s\nwant  %s", mustJSON(t, got), mustJSON(t, want))
		}
	})

	// Findings on later pages (past restPerPage) are collected in API order.
	t.Run("multi_page_pagination", func(t *testing.T) {
		comments := make([]msComment, restPerPage+1)
		for i := range restPerPage {
			comments[i] = msComment{id: int64(i + 1), login: "alice", kind: typenameUser, body: "clean", url: rsURL(int64(i + 1))}
		}
		lastID := int64(restPerPage + 1)
		comments[restPerPage] = msComment{id: lastID, login: "mallory", kind: typenameUser, body: "ping @sourcery-ai", url: rsURL(lastID)}
		got := runMentions(t, defaultMentionRequest(t), msInput{issueComments: comments})
		want := MentionScanResult{
			Protocol: Protocol,
			State:    MentionScanOK,
			Mentions: []MentionFinding{
				{Source: MentionSourceIssueComment, URL: rsURL(lastID), CreatedAt: rsCreated, UpdatedAt: rsCreated},
			},
		}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("got = %s\nwant  %s", mustJSON(t, got), mustJSON(t, want))
		}
	})

	// No body text may appear in the JSON output, whether ok or unreadable.
	t.Run("output_has_no_body_text", func(t *testing.T) {
		const secret = "secret-untrusted-body-marker"
		okIn := msInput{
			issueComments: []msComment{{id: 1, login: "mallory", kind: typenameUser, body: secret + " @sourcery-ai", url: rsURL(1)}},
			lineComments:  []msComment{{id: 2, login: testSourceryBotLogin, kind: typenameBot, body: secret + " @coderabbitai", url: testCommentURL(2)}},
			reviews:       []msReview{{id: 3, login: "bob", kind: typenameUser, body: secret + " @codex", submitted: rsCreated, url: rsReviewURL(3)}},
		}
		okJSON := mustJSON(t, runMentions(t, defaultMentionRequest(t), okIn))
		if strings.Contains(okJSON, secret) {
			t.Errorf("ok JSON leaks body marker: %s", okJSON)
		}
		badIn := msInput{
			issueComments: []msComment{{id: 1, login: "mallory", kind: typenameUser, body: secret + " @sourcery-ai", url: rsURL(1)}},
			edit:          map[MentionScanStage]func(string) string{MentionStageReviews: func(string) string { return "{" + secret }},
			stop:          MentionStageReviews,
		}
		badJSON := mustJSON(t, runMentions(t, defaultMentionRequest(t), badIn))
		if strings.Contains(badJSON, secret) {
			t.Errorf("unreadable JSON leaks body marker: %s", badJSON)
		}
	})
}


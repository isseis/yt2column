func TestParseObservedBotAndValidation(t *testing.T) {
	t.Run("parse_valid", func(t *testing.T) {
		got, err := ParseObservedBot("sourcery=sourcery-ai")
		if err != nil {
			t.Fatalf("ParseObservedBot = %v", err)
		}
		if got.Profile != ProfileSourcery || got.Reviewer.String() != "sourcery-ai" {
			t.Errorf("got = %+v", got)
		}
	})

	for _, tc := range []struct {
		name     string
		raw      string
		noEchoOf []string
	}{
		{"empty", "", nil},
		{"no_equals", "sourcery", []string{"sourcery"}},
		{"empty_profile", "=sourcery-ai", []string{"=sourcery-ai", "sourcery-ai"}},
		{"empty_login", "sourcery=", []string{"sourcery=", "sourcery"}},
		{"unknown_profile", "unknownprof=sourcery-ai", []string{"unknownprof=sourcery-ai", "unknownprof", "sourcery-ai"}},
		{"bot_suffix", "sourcery=sourcery-ai[bot]", []string{"sourcery=sourcery-ai[bot]", "sourcery-ai[bot]"}},
		{"extra_equals", "sourcery=sourcery-ai=extra", []string{"sourcery=sourcery-ai=extra", "sourcery-ai=extra"}},
		{"space_in_login", "coderabbit=bad login", []string{"coderabbit=bad login", "bad login"}},
	} {
		t.Run("parse_invalid/"+tc.name, func(t *testing.T) {
			_, err := ParseObservedBot(tc.raw)
			if !errors.Is(err, ErrInvalidInput) {
				t.Fatalf("ParseObservedBot(%q) = %v, want ErrInvalidInput", tc.raw, err)
			}
			// The error text is the contract here: neither the full input nor
			// either delegated half may be echoed into the error message.
			for _, token := range tc.noEchoOf {
				if strings.Contains(err.Error(), token) {
					t.Errorf("error %q echoes input token %q", err, token)
				}
			}
		})
	}

	// Directly constructed zero, out-of-range, and duplicate ObservedBot values
	// and invalid Requests must fail with ErrInvalidInput before any gh call.
	goodBots := defaultObservedBots(t)
	goodPR := mustPR(t)
	crLogin := mustLogin(t, testReviewer)
	srLogin := mustLogin(t, testSourceryReviewer)
	for name, req := range map[string]MentionScanRequest{
		"zero_pr":             {ObservedBots: goodBots, Requests: defaultMentionRequests},
		"empty_bots":          {PR: goodPR, Requests: defaultMentionRequests},
		"zero_observed_bot":   {PR: goodPR, ObservedBots: []ObservedBot{{}}, Requests: defaultMentionRequests},
		"invalid_profile":     {PR: goodPR, ObservedBots: []ObservedBot{{Profile: ReviewProfile(99), Reviewer: crLogin}}, Requests: defaultMentionRequests},
		"zero_reviewer_login": {PR: goodPR, ObservedBots: []ObservedBot{{Profile: ProfileCodeRabbit}}, Requests: defaultMentionRequests},
		"duplicate_profile":   {PR: goodPR, ObservedBots: []ObservedBot{{Profile: ProfileCodeRabbit, Reviewer: crLogin}, {Profile: ProfileCodeRabbit, Reviewer: srLogin}}, Requests: defaultMentionRequests},
		"duplicate_login":     {PR: goodPR, ObservedBots: []ObservedBot{{Profile: ProfileCodeRabbit, Reviewer: crLogin}, {Profile: ProfileSourcery, Reviewer: crLogin}}, Requests: defaultMentionRequests},
		"empty_requests":      {PR: goodPR, ObservedBots: goodBots},
		"blank_request":       {PR: goodPR, ObservedBots: goodBots, Requests: []string{""}},
		"whitespace_request":  {PR: goodPR, ObservedBots: goodBots, Requests: []string{" @coderabbitai review "}},
		"long_request":        {PR: goodPR, ObservedBots: goodBots, Requests: []string{strings.Repeat("x", maxRequestTextLength+1)}},
		"duplicate_request":   {PR: goodPR, ObservedBots: goodBots, Requests: []string{"@coderabbitai review", "@coderabbitai review"}},
	} {
		t.Run("request/"+name, func(t *testing.T) {
			g, err := NewGitHubWithoutReviewer(cmdrunnertestutil.New(t))
			if err != nil {
				t.Fatal(err)
			}
			if _, err := g.PRMentions(t.Context(), req); !errors.Is(err, ErrInvalidInput) {
				t.Errorf("PRMentions = %v, want ErrInvalidInput", err)
			}
		})
	}
}

func checkEnumNames[T encoding.TextMarshaler](t *testing.T, label string, values []T, want []string) {
	t.Helper()
	got := make([]string, 0, len(values))
	for _, v := range values {
		b, err := v.MarshalText()
		if err != nil {
			t.Fatalf("%s(%v).MarshalText = %v", label, v, err)
		}
		got = append(got, string(b))
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("%s = %v, want %v", label, got, want)
	}
}

func TestMentionEnumsFailClosed(t *testing.T) {
	// Exercise every list helper and verify MarshalText succeeds for every
	// listed value.
	checkEnumNames(t, "MentionScanStates", MentionScanStates(), []string{"unreadable", "ok"})
	checkEnumNames(t, "MentionSources", MentionSources(), []string{"issue-comment", "line-comment", "review"})
	checkEnumNames(t, "MentionScanStages", MentionScanStages(), []string{"repo", "user", "issue-comments", "line-comments", "reviews"})

	// Out-of-range and invalid zero enum values fail closed.
	for name, marshal := range map[string]func() ([]byte, error){
		"scan_state_out_of_range": MentionScanState(99).MarshalText,
		"source_zero_unknown":     MentionSourceUnknown.MarshalText,
		"source_out_of_range":     MentionSource(99).MarshalText,
		"stage_out_of_range":      MentionScanStage(99).MarshalText,
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := marshal(); !errors.Is(err, errUnknownEnum) {
				t.Errorf("err = %v, want errUnknownEnum", err)
			}
		})
	}

	// Zero MentionScanResult marshals as unreadable, and zero MentionFinding
	// fails to marshal because MentionSourceUnknown is invalid.
	zeroJSON := mustJSON(t, MentionScanResult{})
	if !strings.Contains(zeroJSON, `"state":"unreadable"`) {
		t.Errorf("zero MentionScanResult JSON = %s, want state unreadable", zeroJSON)
	}
	if _, err := json.Marshal(MentionFinding{}); !errors.Is(err, errUnknownEnum) {
		t.Errorf("Marshal(zero MentionFinding) = %v, want errUnknownEnum", err)
	}
}
